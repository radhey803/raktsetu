{% macro normalize_blood_group(column_name) %}
CASE
    WHEN UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%OH+%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%OHPOS%' 
      OR UPPER({{ column_name }}) LIKE '%BOMBAY%OH+%' THEN 'Bombay (Oh+)'
    WHEN UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%OH-%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%OHNEG%' 
      OR UPPER({{ column_name }}) LIKE '%BOMBAY%OH-%' THEN 'Bombay (Oh-)'
    WHEN UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%OH%' 
      OR UPPER({{ column_name }}) LIKE '%BOMBAY%' THEN 'Bombay (Oh+)'
    WHEN UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE 'AB+%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%AB+VE%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%ABPOS%' THEN 'AB+'
    WHEN UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE 'AB-%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%AB-VE%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%ABNEG%' THEN 'AB-'
    WHEN UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE 'A+%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%A+VE%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%APOS%' THEN 'A+'
    WHEN UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE 'A-%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%A-VE%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%ANEG%' THEN 'A-'
    WHEN UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE 'B+%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%B+VE%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%BPOS%' THEN 'B+'
    WHEN UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE 'B-%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%B-VE%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%BNEG%' THEN 'B-'
    WHEN UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE 'O+%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%O+VE%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%OPOS%' THEN 'O+'
    WHEN UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE 'O-%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%O-VE%' 
      OR UPPER(REPLACE({{ column_name }}, ' ', '')) LIKE '%ONEG%' THEN 'O-'
    ELSE TRIM({{ column_name }})
END
{% endmacro %}
